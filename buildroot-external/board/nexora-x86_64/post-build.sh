#!/bin/sh
# Buildroot post-build script for Nexora OS (x86-64).
# $1: target directory

set -e

BOARD_DIR="$(dirname "$0")"
TARGET="$1"

# GRUB2 (x86_64-efi) reads its configuration from the EFI system
# partition. The kernel is not on the ESP: each root slot carries its own
# /boot/bzImage (BR2_LINUX_KERNEL_INSTALL_TARGET).
install -D -m 0644 "${BOARD_DIR}/grub.cfg" \
	"${BINARIES_DIR}/efi-part/EFI/BOOT/grub.cfg"
if [ ! -f "${TARGET}/boot/bzImage" ]; then
	echo "post-build.sh: ${TARGET}/boot/bzImage missing (BR2_LINUX_KERNEL_INSTALL_TARGET?)" >&2
	exit 1
fi

# Mount point of the EFI system partition (grubenv); see S01nexora-data.
mkdir -p "${TARGET}/boot/efi"

# /etc/nexora-release: version, build id and board exactly as compiled into
# nexora-console-ui (share/nexora/build-info is generated by CMake).
BUILD_INFO="${TARGET}/usr/share/nexora/build-info"
if [ ! -f "${BUILD_INFO}" ]; then
	echo "post-build.sh: ${BUILD_INFO} missing (nexora-os package not installed?)" >&2
	exit 1
fi
value() {
	sed -n "s/^$1=//p" "${BUILD_INFO}" | head -n 1
}
VERSION=$(value NEXORA_VERSION)
BUILD_ID=$(value NEXORA_BUILD_ID)
BOARD=$(value NEXORA_BOARD)
for v in "${VERSION}" "${BUILD_ID}" "${BOARD}"; do
	case "${v}" in
	"" | *[!A-Za-z0-9._+-]*)
		echo "post-build.sh: unexpected value '${v}' in ${BUILD_INFO}" >&2
		exit 1
		;;
	esac
done
sed -i -e "s/@NEXORA_VERSION@/${VERSION}/g" \
	-e "s/@NEXORA_BUILD_ID@/${BUILD_ID}/g" \
	-e "s/@NEXORA_BOARD@/${BOARD}/g" \
	"${TARGET}/etc/nexora-release"

# Recovery login on tty2 in addition to the serial getty configured by
# BR2_TARGET_GENERIC_GETTY_PORT (ttyS0). tty1 is used by the console UI.
if ! grep -q '^tty2::' "${TARGET}/etc/inittab"; then
	printf '%s\n' \
		'# Recovery login on the second virtual terminal (Nexora)' \
		'tty2::respawn:/sbin/getty 38400 tty2 linux' \
		>> "${TARGET}/etc/inittab"
fi
